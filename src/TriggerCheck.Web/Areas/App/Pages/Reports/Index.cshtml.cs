/// <summary>
/// FEAT-10: monthly SLA report. Every member (viewers too) can view and download it (PDF / CSV) - it only aggregates
/// data they can already see; the monthly e-mail setting is CustomerAdmin only.
/// AI-6: the AI narrative of the selected period (monthly, or an ISO week with <c>?week=yyyy-Www</c>, panel only). Pages
/// never call the model: the narrative is generated by the batch job; a CustomerAdmin can request one for a period that
/// has none (it spends AI budget).
/// </summary>
public class IndexModel(AppDbContext db, ICurrentCustomer current, SlaReportCache reports, SlaReportPdf pdf, TimeProvider time,
    Text<AppResource> L, NarrativeReports narratives) : PageModel
{
    public const int MonthsOffered = 12, WeeksOffered = 9;

    public SlaReport Report { get; private set; } = null!;
    public string Month { get; private set; } = "";
    public List<string> Months { get; private set; } = [];
    public bool MonthlyEmail { get; private set; }
    public string TimeZoneId { get; private set; } = SlaReportService.DefaultTimeZone;
    /// <summary>Selected ISO week ("yyyy-Www"); null for the monthly view.</summary>
    public string? Week { get; private set; }
    public List<string> Weeks { get; private set; } = [];
    public ReportNarrativeModel Narrative { get; private set; } = null!;

    public async Task<IActionResult> OnGetAsync(string? month, string? week, CancellationToken ct)
    {
        if (!await LoadAsync(month, week, ct)) return NotFound();
        var customer = await current.GetCustomerAsync(ct);
        var period = new NarrativePeriod(Week is null ? ReportPeriodKind.Monthly : ReportPeriodKind.Weekly, Report.PeriodKey);
        var view = await narratives.GetAsync(customer, period, Report.TimeZoneId, !Report.IsPartial, ct);
        int? mine = null;
        var userId = User.FindFirstValue(ClaimTypes.NameIdentifier);
        if (view.DecisionId is long id && userId is not null)
            mine = await db.AiFeedback.AsNoTracking().Where(f => f.DecisionId == id && f.UserId == userId && f.CustomerId == customer.Id)
                .Select(f => (int?)f.Value).FirstOrDefaultAsync(ct);
        Narrative = new ReportNarrativeModel(view, Month, Week, User.IsInRole(Roles.CustomerAdmin), mine,
            Request.Path + Request.QueryString);
        return Page();
    }

    /// <summary>CustomerAdmin: queue the AI narrative of the selected complete period for the batch job.</summary>
    public async Task<IActionResult> OnPostNarrativeAsync(string? month, string? week, CancellationToken ct)
    {
        if (!User.IsInRole(Roles.CustomerAdmin)) return Forbid();
        if (!await LoadAsync(month, week, ct)) return NotFound();
        if (Report.IsPartial)
        {
            TempData["Error"] = L["The AI narrative is available once the period is over."].Value;
            return RedirectToPage(new { month = Week is null ? Month : null, week = Week });
        }
        var customer = await current.GetCustomerAsync(ct);
        var period = new NarrativePeriod(Week is null ? ReportPeriodKind.Monthly : ReportPeriodKind.Weekly, Report.PeriodKey);
        switch (await narratives.RequestAsync(customer, period, Report.TimeZoneId, ct))
        {
            case NarrativeRequestResult.Queued or NarrativeRequestResult.AlreadyQueued:
                TempData["Success"] = L["The AI narrative is being prepared. It appears here within a few minutes."].Value;
                break;
            case NarrativeRequestResult.CoolingDown:
                TempData["Error"] = L["The AI narrative was tried recently. Please try again later."].Value;
                break;
            case NarrativeRequestResult.OverBudget:
                TempData["Error"] = L["The AI budget of this month is used up."].Value;
                break;
            default:
                TempData["Error"] = L["AI narratives are not available for your account."].Value;
                break;
        }
        return RedirectToPage(new { month = Week is null ? Month : null, week = Week });
    }

    public async Task<IActionResult> OnGetPdfAsync(string? month, CancellationToken ct)
    {
        if (!await LoadAsync(month, null, ct)) return NotFound();
        Response.Headers.CacheControl = "no-store";
        return File(pdf.Render(Report), "application/pdf", ReportingSetup.FileName(Report.MonthKey, "pdf"));
    }

    public async Task<IActionResult> OnGetCsvAsync(string? month, CancellationToken ct)
    {
        if (!await LoadAsync(month, null, ct)) return NotFound();
        Response.Headers.CacheControl = "no-store";
        return File(SlaReportCsv.Render(Report), "text/csv; charset=utf-8", ReportingSetup.FileName(Report.MonthKey, "csv"));
    }

    /// <summary>CustomerAdmin: monthly e-mail opt-in and the report time zone.</summary>
    public async Task<IActionResult> OnPostSettingsAsync(bool monthlyEmail, string? timeZoneId, string? month, CancellationToken ct)
    {
        if (!User.IsInRole(Roles.CustomerAdmin)) return Forbid();
        var zone = string.IsNullOrWhiteSpace(timeZoneId) ? SlaReportService.DefaultTimeZone : timeZoneId.Trim();
        if (MaintenanceSchedule.FindTimeZone(zone) is null)
        {
            TempData["Error"] = L["Unknown time zone."].Value;
            return RedirectToPage(new { month });
        }
        var cid = current.RequiredCustomerId;
        await db.Customers.Where(c => c.Id == cid).ExecuteUpdateAsync(u => u
            .SetProperty(c => c.MonthlyReportEmail, monthlyEmail)
            .SetProperty(c => c.ReportTimeZoneId, zone == SlaReportService.DefaultTimeZone ? null : zone), ct);
        TempData["Success"] = L["Report settings saved."].Value;
        return RedirectToPage(new { month });
    }

    /// <summary>
    /// Parses "yyyy-MM" (default: the previous month in the report time zone) or, when <paramref name="week"/> is given,
    /// an ISO week "yyyy-Www" of the last <see cref="WeeksOffered"/> weeks. False for invalid input.
    /// </summary>
    private async Task<bool> LoadAsync(string? month, string? week, CancellationToken ct)
    {
        var cid = current.RequiredCustomerId;
        var customer = await current.GetCustomerAsync(ct);
        MonthlyEmail = customer.MonthlyReportEmail;
        TimeZoneId = customer.ReportTimeZoneId ?? SlaReportService.DefaultTimeZone;
        var tz = SlaReportService.ResolveZone(TimeZoneId);
        var local = MaintenanceSchedule.UtcToLocal(time.GetUtcNow().UtcDateTime, tz);
        var thisMonth = new DateTime(local.Year, local.Month, 1);
        Months = Enumerable.Range(0, MonthsOffered).Select(i => thisMonth.AddMonths(-i).ToString("yyyy-MM", CultureInfo.InvariantCulture)).ToList();

        DateTime selected;
        if (string.IsNullOrWhiteSpace(month)) selected = thisMonth.AddMonths(-1);
        else if (!DateTime.TryParseExact(month, "yyyy-MM", CultureInfo.InvariantCulture, DateTimeStyles.None, out selected)
                 || selected.Year < 2000 || selected > thisMonth) return false;
        Month = selected.ToString("yyyy-MM", CultureInfo.InvariantCulture);
        if (!Months.Contains(Month)) Months.Add(Month);

        var today = local.Date;
        Weeks = Enumerable.Range(0, WeeksOffered).Select(i => SlaReportService.WeekKey(today.AddDays(-7 * i))).ToList();
        if (!string.IsNullOrWhiteSpace(week))
        {
            if (!Weeks.Contains(week) || !SlaReportService.TryParseWeekKey(week, out var isoYear, out var isoWeek)) return false;
            Week = week;
            Report = (await reports.GetWeekAsync(cid, isoYear, isoWeek, TimeZoneId, ct))!;
            return true;
        }
        Report = (await reports.GetAsync(cid, selected.Year, selected.Month, TimeZoneId, ct))!;
        return true;
    }
}

/// <summary>Model of the "_ReportNarrative" partial (AI-6).</summary>
/// <param name="Month">Selected month (the monthly view's key; kept for the request form).</param>
/// <param name="Week">Selected week, null in the monthly view.</param>
/// <param name="CanRequest">The viewer is a CustomerAdmin.</param>
/// <param name="MyFeedback">The current user's vote on the narrative (+1 / -1 / null).</param>
public sealed record ReportNarrativeModel(NarrativeView View, string Month, string? Week, bool CanRequest, int? MyFeedback, string ReturnUrl)
{
    /// <summary>A narrative text ready to show: placeholders rendered from the stored values, labels replaced with names.</summary>
    public string Text(string text) => View.Output?.Render(text, View.Names) ?? text;
}
