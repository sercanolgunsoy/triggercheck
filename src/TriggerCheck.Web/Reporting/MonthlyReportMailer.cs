/// <summary>Settings of SLA reports (section <c>Reports</c>).</summary>
public sealed class ReportOptions
{
    public const string Section = "Reports";
    /// <summary>How often the monthly e-mail job looks for due reports; 0 = disabled.</summary>
    public int JobIntervalMinutes { get; set; } = 60;
    /// <summary>The previous month's report is still sent this many days into the new month (catch-up after downtime).</summary>
    public int CatchUpDays { get; set; } = 7;
    /// <summary>How long the PDF download link in the e-mail works.</summary>
    public int DownloadLinkDays { get; set; } = 30;
}

/// <summary>A verified report download token.</summary>
public sealed record ReportLinkToken(int CustomerId, int Year, int Month, string TimeZoneId);

/// <summary>
/// Download links of e-mailed reports: customer, month and time zone protected with ASP.NET Core Data Protection
/// (authenticated encryption with an expiry). Chosen over attaching the PDF so the e-mail outbox schema stays as it is;
/// the link is a bearer link to one aggregate report only (no targets or error texts), expires after
/// <see cref="ReportOptions.DownloadLinkDays"/> days and stops working when the customer is suspended.
/// </summary>
public sealed class ReportLinks(IDataProtectionProvider dataProtection, IOptions<ReportOptions> options, PublicUrls urls)
{
    public const string Purpose = "SlaReportDownload.v1";
    public const string DownloadPath = "/reports/download";

    private ITimeLimitedDataProtector Protector => dataProtection.CreateProtector(Purpose).ToTimeLimitedDataProtector();

    /// <summary>Wall-clock expiry: the protector checks it against the system clock.</summary>
    public string CreateToken(int customerId, int year, int month, string timeZoneId) =>
        Protector.Protect(string.Create(CultureInfo.InvariantCulture, $"{customerId}|{year}|{month}|{timeZoneId}"),
            DateTimeOffset.UtcNow.AddDays(Math.Clamp(options.Value.DownloadLinkDays, 1, 365)));

    public string Url(int customerId, int year, int month, string timeZoneId) =>
        $"{urls.BaseUrl}{DownloadPath}?token={Uri.EscapeDataString(CreateToken(customerId, year, month, timeZoneId))}";

    public bool TryRead(string? token, out ReportLinkToken? result)
    {
        result = null;
        if (string.IsNullOrWhiteSpace(token) || token.Length > 2048) return false;
        string payload;
        try { payload = Protector.Unprotect(token, out _); }
        catch (CryptographicException) { return false; }
        catch (FormatException) { return false; }
        var p = payload.Split('|');
        if (p.Length != 4 || !int.TryParse(p[0], NumberStyles.None, CultureInfo.InvariantCulture, out var cid)
            || !int.TryParse(p[1], NumberStyles.None, CultureInfo.InvariantCulture, out var y)
            || !int.TryParse(p[2], NumberStyles.None, CultureInfo.InvariantCulture, out var m) || m is < 1 or > 12)
            return false;
        result = new ReportLinkToken(cid, y, m, p[3]);
        return true;
    }
}

/// <summary>
/// Monthly SLA report e-mail (FEAT-10, opt-in per customer): in the first <see cref="ReportOptions.CatchUpDays"/> days
/// of a month (in the customer's report time zone) the previous month's report goes to the customer's active admins
/// (or the contact address when there are none) through the e-mail outbox, with the key figures and a signed PDF
/// download link. Idempotent per customer and month: the <see cref="MonthlyReportDelivery"/> row (unique) and the
/// outbox rows are saved in ONE transaction, so parallel instances never send twice and a failure (report, database)
/// leaves nothing claimed - the next run retries.
/// <para>
/// AI-6: when an AI narrative is expected for the month (<see cref="NarrativeReports.ForMailAsync"/>) the e-mail is held
/// back for this run, at most until Ai:Narrative:EmailWaitMinutes after the month ended; a ready narrative is included,
/// otherwise the e-mail goes without it. AI never blocks or fails the e-mail: the lookup does not throw, and the
/// narrative is generated by its own batch job, never here. A narrative that becomes ready after the e-mail was sent
/// does not cause a second e-mail (the delivery row exists).
/// </para>
/// </summary>
public sealed class MonthlyReportMailer(AppDbContext db, SlaReportService reports, ReportLinks links, AppEmailSignal signal, PublicUrls urls,
    TimeProvider time, IOptionsMonitor<ReportOptions> options, Text<SharedResource> L, ILogger<MonthlyReportMailer> logger,
    NarrativeReports narratives)
{
    public async Task<int> RunAsync(CancellationToken ct)
    {
        var now = time.GetUtcNow().UtcDateTime;
        var customers = await db.Customers.AsNoTracking().Where(c => c.IsActive && c.MonthlyReportEmail)
            .Select(c => new { c.Id, c.ReportTimeZoneId }).ToListAsync(ct);
        var sent = 0;
        foreach (var c in customers)
        {
            var tz = SlaReportService.ResolveZone(c.ReportTimeZoneId);
            var local = MaintenanceSchedule.UtcToLocal(now, tz);
            if (local.Day > Math.Max(1, options.CurrentValue.CatchUpDays)) continue;
            var month = new DateTime(local.Year, local.Month, 1).AddMonths(-1);
            var key = month.ToString("yyyy-MM", CultureInfo.InvariantCulture);
            try
            {
                if (await db.MonthlyReportDeliveries.AnyAsync(d => d.CustomerId == c.Id && d.Month == key, ct)) continue;
                var (_, monthEnd) = SlaReportService.MonthRange(month.Year, month.Month, tz);
                var narrative = await narratives.ForMailAsync(c.Id, key, NarrativeReportJob.ZoneId(c.ReportTimeZoneId), monthEnd, ct);
                if (narrative.Wait) continue; // the AI narrative is still being prepared; a later run sends (with or without it)
                var report = await reports.BuildAsync(c.Id, month.Year, month.Month, c.ReportTimeZoneId, ct);
                if (report is null) continue;
                var (subject, body, recipients) = await ComposeAsync(report, narrative, ct);

                // Reads are done: the transaction only writes (SQLite takes the write lock at once).
                await using var transaction = await db.Database.BeginTransactionAsync(ct);
                db.MonthlyReportDeliveries.Add(new MonthlyReportDelivery { CustomerId = c.Id, Month = key, SentAtUtc = now });
                foreach (var address in recipients) OutboxRows.Add(db, address, subject, body, now);
                try
                {
                    await db.SaveChangesAsync(ct);
                    await transaction.CommitAsync(ct);
                }
                catch (DbUpdateException)
                {
                    await transaction.RollbackAsync(CancellationToken.None);
                    continue; // another instance claimed it
                }
                sent++;
            }
            catch (Exception ex) when (!ct.IsCancellationRequested)
            {
                logger.LogError(ex, "Monthly report for customer {CustomerId} ({Month}) failed; it is retried on the next run.", c.Id, key);
            }
            finally { db.ChangeTracker.Clear(); }
        }
        if (sent > 0) signal.Notify();
        return sent;
    }

    private async Task<(string Subject, string Body, List<string> Recipients)> ComposeAsync(SlaReport r, MailNarrative narrative, CancellationToken ct)
    {
        var s = r.Summary;
        var lines = new List<string>
        {
            L["Your TriggerCheck SLA report for {0} ({1}):", r.MonthKey, r.TimeZoneId],
            string.Join("\n",
                L["Uptime: {0}", Fmt.Percent(s.UptimePercent)].Value,
                L["Downtime: {0}", SlaReportPdf.Minutes(s.DowntimeMinutes)].Value,
                L["Incidents: {0}", s.IncidentCount].Value,
                L["MTTR: {0}", SlaReportPdf.Minutes(s.MttrMinutes)].Value,
                L["SLA targets met: {0}, missed: {1}", s.SlaMet, s.SlaMissed].Value)
        };
        var missed = r.Monitors.Where(m => m.SlaMet == false).Select(m => $"- {m.Name}: {Fmt.Percent(m.UptimePercent)} < {Fmt.Percent(m.SlaTarget)}").ToList();
        if (missed.Count > 0) lines.Add(L["Missed SLA targets:"] + "\n" + string.Join("\n", missed));
        if (narrative.Output is { } n) lines.Add(NarrativeText(n, narrative.Names));
        lines.Add(L["Download the PDF (link valid for {0} days): {1}", options.CurrentValue.DownloadLinkDays, links.Url(r.CustomerId, r.Year, r.Month, r.TimeZoneId)]);
        lines.Add(L["All reports: {0}", $"{urls.BaseUrl}/App/Reports?month={r.MonthKey}"]);
        lines.Add(L["You receive this e-mail because monthly reports are enabled on the Reports page. An admin can turn them off there."]);

        var adminRoleId = await db.Roles.Where(x => x.Name == Roles.CustomerAdmin).Select(x => x.Id).FirstOrDefaultAsync(ct);
        var recipients = await db.Users.Where(u => u.CustomerId == r.CustomerId && u.IsActive && u.Email != null
                && db.UserRoles.Any(ur => ur.UserId == u.Id && ur.RoleId == adminRoleId))
            .Select(u => u.Email!).ToListAsync(ct);
        if (recipients.Count == 0 && await db.Customers.Where(c => c.Id == r.CustomerId).Select(c => c.ContactEmail).FirstOrDefaultAsync(ct) is { Length: > 0 } contact)
            recipients.Add(contact);
        return (L["TriggerCheck SLA report {0}", r.MonthKey], string.Join("\n\n", lines), recipients.Distinct(StringComparer.OrdinalIgnoreCase).ToList());
    }
    /// <summary>The AI-6 narrative as plain text (in the customer's AI language; monitor labels replaced by names).</summary>
    private string NarrativeText(NarrativeOutput n, IReadOnlyDictionary<string, string>? names)
    {
        var parts = new List<string> { L["AI summary (AI-generated, may be wrong; all figures are from the report):"] + "\n" + NarrativeReports.WithNames(n.Headline, names) };
        void Section(string title, IReadOnlyList<NarrativeItem> items)
        {
            if (items.Count > 0) parts.Add(title + "\n" + string.Join("\n", items.Select(i => "- " + NarrativeReports.WithNames(i.Text, names))));
        }
        Section(L["What happened:"], n.WhatHappened);
        Section(L["What changed:"], n.WhatChanged);
        Section(L["What to watch:"], n.WhatToWatch);
        return string.Join("\n\n", parts);
    }
}

/// <summary>Runs <see cref="MonthlyReportMailer"/> every <see cref="ReportOptions.JobIntervalMinutes"/> (0 = disabled).</summary>
public sealed class MonthlyReportService(IServiceScopeFactory scopes, IOptionsMonitor<ReportOptions> options, TimeProvider time,
    ILogger<MonthlyReportService> logger) : BackgroundService
{
    protected override async Task ExecuteAsync(CancellationToken stoppingToken)
    {
        var minutes = options.CurrentValue.JobIntervalMinutes;
        if (minutes <= 0) return;
        // E-mails of background work are sent in English (the default UI language).
        CultureInfo.CurrentUICulture = new CultureInfo("en");
        try { await Task.Delay(TimeSpan.FromMinutes(2), time, stoppingToken); }
        catch (OperationCanceledException) { return; }
        using var timer = new PeriodicTimer(TimeSpan.FromMinutes(minutes), time);
        do
        {
            try
            {
                using var scope = scopes.CreateScope();
                await scope.ServiceProvider.GetRequiredService<MonthlyReportMailer>().RunAsync(stoppingToken);
            }
            catch (Exception ex) when (!stoppingToken.IsCancellationRequested)
            {
                logger.LogError(ex, "Monthly report job failed.");
            }
        } while (await timer.WaitForNextTickAsync(stoppingToken));
    }
}
